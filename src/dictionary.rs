/// Looks up a word by canonical name or variation (case-insensitive).
pub fn find_word(query: &str) -> Option<&'static WordEntry> {
    let q = query.to_lowercase();
    for entry in SYLHETI_WORDS {
        if entry.canonical_roman == q {
            return Some(entry);
        }
        for v in entry.variations {
            if *v == q {
                return Some(entry);
            }
        }
    }
    None
}
